const dictionaries = { de, en };
export type Lang = keyof typeof dictionaries;

export function detectLang(): Lang {
  const nav = (navigator.language || "en").toLowerCase();
  return nav.startsWith("de") ? "de" : "en";
}

export function resolveLang(setting: string): Lang {
  return setting === "de" || setting === "en" ? setting : detectLang();
}

export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  let s: string = dictionaries[lang][key] ?? de[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

export type TFn = (key: TKey, vars?: Record<string, string | number>) => string;

export function useT(): TFn {
  const lang = useStore((s) => resolveLang(s.settings.language));
  return (key, vars) => translate(lang, key, vars);
}

/** For use outside of React components. */
export function t(key: TKey, vars?: Record<string, string | number>): string {
  return translate(resolveLang(useStore.getState().settings.language), key, vars);
}
